// Generates js/data/pose-refs.js — the Tier-1 scoring references.
// The same data that animates the instructor IS the reference the camera
// compares you against (Doc 06 §4): procedural moves are sampled through the
// FK skeleton; capture clips through their joint positions. All are reduced
// to the shared 7-channel angle signature from engine/pose.js.
//
// Usage: node scripts/gen-pose-refs.mjs

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fk, samplePose, decodeClip, captureJoint } from "../js/viewer3d.js";
import { MOVES } from "../js/moves3d.js";
import { normalizePose, angleFeatures, ANGLE_CHANNELS } from "../js/engine/pose.js";
import capture85 from "../js/data/capture85.js";

const FPS = 30;

// world (y-up) → engine convention (y-down, like camera image space)
function flipY(p) { return [p[0], -p[1], p[2]]; }

function fkToCore(J) {
  return {
    kp: {
      shoulderL: flipY(J.lSh), shoulderR: flipY(J.rSh),
      elbowL: flipY(J.lElbow), elbowR: flipY(J.rElbow),
      wristL: flipY(J.lHand), wristR: flipY(J.rHand),
      hipL: flipY(J.lHip), hipR: flipY(J.rHip),
      kneeL: flipY(J.lKnee), kneeR: flipY(J.rKnee),
      ankleL: flipY(J.lAnkle), ankleR: flipY(J.rAnkle),
    },
    vis: 1,
  };
}

const CMU_MAP = {
  shoulderL: "LeftArm", shoulderR: "RightArm",
  elbowL: "LeftForeArm", elbowR: "RightForeArm",
  wristL: "LeftHand", wristR: "RightHand",
  hipL: "LeftUpLeg", hipR: "RightUpLeg",
  kneeL: "LeftLeg", kneeR: "RightLeg",
  ankleL: "LeftFoot", ankleR: "RightFoot",
};

function captureToCore(clip, frame, idxByName) {
  const kp = {};
  for (const [core, cmu] of Object.entries(CMU_MAP)) {
    kp[core] = flipY(captureJoint(clip, frame, idxByName[cmu]));
  }
  return { kp, vis: 1 };
}

function round3(frames) {
  return frames.map((f) => f.map((v) => (Number.isFinite(v) ? Math.round(v * 1000) / 1000 : null)));
}

const refs = {};

// procedural moves: one full cycle at 30fps
for (const [id, move] of Object.entries(MOVES)) {
  const cycleSec = (move.beats * 60) / move.bpm;
  const n = Math.max(12, Math.round(cycleSec * FPS));
  const frames = [];
  for (let i = 0; i < n; i++) {
    const pose = normalizePose(fkToCore(fk(samplePose(move, i / n))));
    frames.push(angleFeatures(pose));
  }
  refs[id] = { fps: FPS, bpm: move.bpm, beats: move.beats, source: "procedural", frames: round3(frames) };
}

// capture clips: real motion references (trim long ones to 8s)
for (const raw of capture85.clips) {
  if (raw.id === "capture.85_12" || raw.id === "capture.85_08") continue; // keep refs light; loop version covers 85_08
  const clip = decodeClip(raw);
  const idxByName = {};
  clip.joints.forEach((j, i) => { idxByName[j.name] = i; });
  for (const cmu of Object.values(CMU_MAP)) {
    if (!(cmu in idxByName)) throw new Error(`${raw.id}: missing joint ${cmu}`);
  }
  const n = Math.min(clip.nFrames, 8 * FPS);
  const frames = [];
  for (let f = 0; f < n; f++) {
    const pose = normalizePose(captureToCore(clip, f, idxByName));
    frames.push(angleFeatures(pose));
  }
  refs[raw.id] = { fps: clip.fps, source: "capture", frames: round3(frames) };
}

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "js", "data", "pose-refs.js");
writeFileSync(out,
  `// GENERATED by scripts/gen-pose-refs.mjs — Tier-1 scoring references\n` +
  `// derived from the instructor animations and CMU capture clips.\n` +
  `export const CHANNELS = ${JSON.stringify(ANGLE_CHANNELS)};\n` +
  `export default ${JSON.stringify(refs)};\n`);
console.log(`wrote ${out}: ${Object.keys(refs).length} references (${Object.keys(refs).join(", ")})`);
