#!/usr/bin/env node
// =============================================================================
//  generate-guide-reference.mjs — the reference half of the user guide,
//                                 derived from the code rather than written
// =============================================================================
//  A hand-written manual is a claim about the app that nothing checks. It is
//  accurate the day it ships and wrong the first time a route is renamed, and a
//  wrong manual is worse than none because it carries authority — the reader
//  believes it and blames themselves.
//
//  So this half is never written. It is read out of the app itself:
//
//    pages        every route a signed-in person can visit
//    endpoints    every API route, its methods, and the roles allowed to call it
//    public       what is reachable with no account at all, and why
//
//  Regenerate after any routing or authz change:
//    node scripts/generate-guide-reference.mjs           # writes docs/REFERENCE.md
//    node scripts/generate-guide-reference.mjs --json    # machine-readable
//    node scripts/generate-guide-reference.mjs --check   # fail if out of date
//
//  --check is the point: it makes a stale reference a build failure instead of
//  a quiet lie.
// =============================================================================
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const APP = resolve(ROOT, "src/app");
const OUT = resolve(ROOT, "docs/REFERENCE.md");

// ── walk ────────────────────────────────────────────────────────────────────
function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = resolve(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = existsSync(APP) ? walk(APP) : [];

function routeOf(file) {
  return "/" + relative(APP, dirname(file)).replace(/\\/g, "/");
}
const tidy = (r) => (r === "/." || r === "/" ? "/" : r.replace(/\/$/, ""));

// ── roles, read from authz.ts rather than restated here ─────────────────────
// Restating them would create a second source of truth that drifts silently —
// the guide would keep describing a permission model the app had moved on from.
const authz = readFileSync(resolve(ROOT, "src/lib/authz.ts"), "utf8");
const ROLE_SETS = {};
for (const m of authz.matchAll(/export const ([A-Z_]+):\s*Role\[\]\s*=\s*\[([^\]]*)\]/g)) {
  ROLE_SETS[m[1]] = m[2].split(",").map((s) => s.trim().replace(/["']/g, "")).filter(Boolean);
}
if (!Object.keys(ROLE_SETS).length) {
  console.error("✖ no role sets found in src/lib/authz.ts — refusing to emit a reference with no permission model");
  process.exit(1);
}

// ── public surface, read from the middleware ────────────────────────────────
const mw = readFileSync(resolve(ROOT, "src/middleware.ts"), "utf8");
const publicPaths = (mw.match(/const PUBLIC_PATHS = \[([^\]]*)\]/)?.[1] ?? "")
  .split(",").map((s) => s.trim().replace(/["']/g, "")).filter(Boolean);
const publicApi = [...mw.matchAll(/\{\s*method:\s*"([A-Z]+)",\s*prefix:\s*"([^"]+)"/g)]
  .map((m) => ({ method: m[1], path: m[2] }));

// ── pages ───────────────────────────────────────────────────────────────────
const pages = files.filter((f) => f.endsWith("page.tsx") && !f.includes("/api/"))
  .map((f) => tidy(routeOf(f)))
  .sort();

// ── endpoints ───────────────────────────────────────────────────────────────
const endpoints = files.filter((f) => f.endsWith("route.ts")).map((f) => {
  const src = readFileSync(f, "utf8");
  const route = tidy(routeOf(f));
  const methods = [...src.matchAll(/export async function (GET|POST|PUT|PATCH|DELETE)/g)].map((m) => m[1]);
  // The role set named at the call site. Where a handler names none, that is
  // reported as "not role-gated" rather than guessed at — an endpoint whose
  // protection cannot be determined must look unresolved, not open or closed.
  const sets = [...new Set([...src.matchAll(/requireRole\(([A-Z_]+)\)/g)].map((m) => m[1]))];
  const roles = [...new Set(sets.flatMap((s) => ROLE_SETS[s] ?? []))];
  const isPublic = publicApi.some((p) => route === p.path || route.startsWith(p.path + "/"));
  return { route, methods, sets, roles, isPublic };
}).sort((a, b) => a.route.localeCompare(b.route));

// ── render ──────────────────────────────────────────────────────────────────
const stamp = "<!-- GENERATED by scripts/generate-guide-reference.mjs — do not edit by hand -->";
const lines = [stamp, "", "# SupersDeck — reference", "",
  "Everything the app exposes, read out of the code. If this disagrees with the",
  "app, the app is right and this file is stale — regenerate it.", "",
  `**Roles:** ${[...new Set(Object.values(ROLE_SETS).flat())].sort().join(", ")}`, "",
  "## Permission groups", "",
  "| group | roles | used for |", "|---|---|---|",
];
const GROUP_NOTE = {
  WRITE_ASM: "most writes", WRITE_ASMP: "work orders and heat-log entries",
  ADMIN_ONLY: "deletes and reference data", CLOUD_ACCESS: "the cloud drive",
};
for (const [k, v] of Object.entries(ROLE_SETS)) {
  lines.push(`| \`${k}\` | ${v.join(", ")} | ${GROUP_NOTE[k] ?? "—"} |`);
}

lines.push("", "## Pages", "", `${pages.length} screens.`, "");
for (const p of pages) lines.push(`- \`${p}\``);

lines.push("", "## Reachable without signing in", "",
  "These are open by design. Everything else redirects to `/login`.", "");
for (const p of publicPaths) lines.push(`- \`${p}\` (and anything beneath it)`);
for (const p of publicApi) lines.push(`- \`${p.method} ${p.path}\``);

lines.push("", "## Endpoints", "", `${endpoints.length} API routes.`, "",
  "| endpoint | methods | who can call it |", "|---|---|---|");
for (const e of endpoints) {
  const who = e.isPublic ? "**anyone** (public by design)"
    : e.roles.length ? e.roles.join(", ")
    : "any signed-in user (not role-gated)";
  lines.push(`| \`${e.route}\` | ${e.methods.join(", ") || "—"} | ${who} |`);
}
lines.push("");

const rendered = lines.join("\n");
const data = { roles: ROLE_SETS, pages, publicPaths, publicApi, endpoints };

if (process.argv.includes("--json")) { console.log(JSON.stringify(data, null, 2)); process.exit(0); }

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== rendered) {
    console.error("✖ docs/REFERENCE.md is out of date — the app has routes or permissions this file does not describe.");
    console.error("  Run: node scripts/generate-guide-reference.mjs");
    process.exit(1);
  }
  console.log(`  ✔ reference current — ${pages.length} pages, ${endpoints.length} endpoints`);
  process.exit(0);
}

writeFileSync(OUT, rendered);
console.log(`  ✔ wrote docs/REFERENCE.md — ${pages.length} pages, ${endpoints.length} endpoints, ${Object.keys(ROLE_SETS).length} permission groups`);
